FILLER = [64, 71, 97, 182, 188, 195, 228, 320, 334, 338, 344, 424]   # 识别成“嗯”“哎”“对”“是”的：咂嘴声（录音里压成静音）或吸气声，不出字幕
for i in FILLER: F[i] = ''
segs = [F.get(i, g(auto[i])) for i in range(len(auto))]
if __name__ == '__main__':
    # 合成字幕行：一段里按标点切，每行不超过 20 个字（不算标点）；段与段之间不接（停顿就是换行处）
    lines = []
    cnt = lambda s: len(re.findall(r'[一-鿿0-9A-Za-z]', s))
    for seg in (q for s in segs for q in s.split('|')):         # “|”：这里一定换行
        seg = seg.strip()
        if not re.search(r'[一-鿿0-9]', seg): continue
        parts = re.findall(r'[^，。？！；：、…]+[，。？！；：、…”’]*', seg)
        cur = ''
        for p in parts:
            if cur and (cnt(cur) + cnt(p) > 20 or cur.endswith('”')): lines.append(cur); cur = p     # 引文结束处也换行
            else: cur += p
        if cur: lines.append(cur)
    out = []
    for l in lines:     # 两个字以内的短行：句子说完了（。？！”）就接到上一行后面，没说完就接到下一行前面
        if out and cnt(l) <= 2 and re.search(r'[。？！”]$', l) and not out[-1].endswith('”') and cnt(out[-1]) + cnt(l) <= 22: out[-1] += l
        elif out and cnt(out[-1]) <= 2 and not re.search(r'[…。？！”]$', out[-1]) and cnt(out[-1]) + cnt(l) <= 22: out[-1] += l
        else: out.append(l)
    open('rec/part10_fixed.txt', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(len(out), 'subtitle lines;', sum(cnt(l) for l in out), 'characters')
