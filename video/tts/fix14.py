        parts = re.findall(r'[^，。？！；：、…—]+[，。？！；：、…—”’]*', seg)
        cur = ''
        for p in parts:
            if cur and (cnt(cur) + cnt(p) > 20 or cur.endswith('”')): lines.append(cur); cur = p     # 引文结束处也换行
            else: cur += p
